// Shared helpers for the translation tooling: read the English maps in
// lib/l10n/en/*.dart into plain objects, and write language maps back out as
// Dart with correct escaping.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const EN_DIR = path.join(ROOT, 'lib', 'l10n', 'en');
export const LANG_DIR = path.join(ROOT, 'lib', 'l10n', 'lang');
export const GROUPS = ['common', 'auth', 'account', 'shop', 'orders', 'wholesale', 'search_tools'];

const BACKSLASH = String.fromCharCode(92);

// Parses one Dart string literal starting at src[i] (a quote). Returns [value, nextIndex].
function readLiteral(src, i) {
  const q = src[i];
  let out = '';
  i++;
  while (i < src.length && src[i] !== q) {
    if (src[i] === BACKSLASH) {
      const n = src[i + 1];
      out += n === 'n' ? '\n' : n === 't' ? '\t' : n;
      i += 2;
    } else out += src[i++];
  }
  return [out, i + 1];
}

/** Reads `'key': 'value' 'adjacent',` entries from one English .dart file. */
export function readEnglish(group) {
  const src = fs.readFileSync(path.join(EN_DIR, `${group}.dart`), 'utf8').replace(/\r\n/g, '\n');
  const body = src.slice(src.indexOf('{'));
  const map = {};
  let i = 0;
  const skipWs = () => { while (i < body.length && /\s/.test(body[i])) i++; };
  while (i < body.length) {
    skipWs();
    if (body.startsWith('//', i)) { while (i < body.length && body[i] !== '\n') i++; continue; }
    if (body[i] === "'" || body[i] === '"') {
      let key;
      [key, i] = readLiteral(body, i);
      skipWs();
      if (body[i] !== ':') throw new Error(`${group}: expected ":" after ${key}`);
      i++;
      skipWs();
      let value = '';
      while (body[i] === "'" || body[i] === '"') {
        let part;
        [part, i] = readLiteral(body, i);
        value += part;
        skipWs();
      }
      if (map[key] !== undefined) throw new Error(`${group}: duplicate key ${key}`);
      map[key] = value;
      if (body[i] === ',') i++;
    } else i++;
  }
  return map;
}

export function readAllEnglish() {
  const all = {};
  for (const g of GROUPS) {
    for (const [k, v] of Object.entries(readEnglish(g))) {
      if (all[k] !== undefined) throw new Error(`key defined in two groups: ${k}`);
      all[k] = v;
    }
  }
  return all;
}

/** The {name} placeholders in a string, sorted, as a comparable string. */
export const placeholders = s => [...String(s).matchAll(/\{(\w+)\}/g)].map(m => m[1]).sort().join(',');

const dartString = s => {
  const escaped = s
    .split(BACKSLASH).join(BACKSLASH + BACKSLASH)
    .split("'").join(BACKSLASH + "'")
    .split('$').join(BACKSLASH + '$')
    .split('\n').join(BACKSLASH + 'n');
  return `'${escaped}'`;
};

export function writeLangDart(code, map) {
  const lines = Object.keys(map).map(k => `  ${dartString(k)}: ${dartString(map[k])},`);
  const text = `/// Translations for '${code}'. Key -> text; a missing key falls back to English.\n/// Generated by tool/l10n/build_lang.mjs from the translated JSON -- edit the JSON, not this.\nconst Map<String, String> strings = {\n${lines.join('\n')}\n};\n`;
  fs.writeFileSync(path.join(LANG_DIR, `${code}.dart`), text.replace(/\n/g, '\r\n'));
}
